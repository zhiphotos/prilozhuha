/** Какое напоминание отправить этому человеку сегодня. Возвращает { title, body, go } или null, если лучше промолчать. */
export function pickMessage(sub, nowMs) {
  const stats = sub.stats ?? {};
  const days = (a) => Math.floor((nowMs - a) / 86400000);
  const idle = sub.lastSeen ? days(sub.lastSeen) : 99;
  const seq = Number(sub.seq ?? 0);
  // Давно не заходил: не чаще раза в неделю и не дольше двух месяцев, потом тишина.
  if (idle >= 60) return null;
  if (idle >= 7) {
    if (sub.lastSent && days(sub.lastSent) < 7) return null;
    return LAPSED[seq % LAPSED.length];
  }
  if (stats.paid && Number(stats.lessonsDone ?? 0) < 6 && seq % 3 === 0) {
    const n = Math.min(6, Number(stats.lessonsDone ?? 0) + 1);
    return LESSON(n, LESSON_TITLES[n - 1]);
  }
  const started = Number(stats.people ?? 0) > 0 || Number(stats.pages ?? 0) > 1;
  const list = started ? STARTED : NEW;
  return list[seq % list.length];
}
