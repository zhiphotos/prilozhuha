const id = () => crypto.randomUUID();
type Text = Extract<PageBlock, { type: "text" }>;
const text = (p: Partial<Text> & Pick<Text, "x" | "y" | "w">): Text => ({ id: id(), type: "text", text: "", font: "serif", size: "md", ...p });
const slot = (x: number, y: number, w: number, h: number, label: string, frame: PhotoFrame = "polaroid", rotate = 0): PageBlock => ({ id: id(), type: "slot", x, y, w, h, label, frame, rotate });
const pill = (x: number, y: number, w: number, label: string) => text({ x, y, w, text: label, font: "sans", size: "sm", look: "pill" });

function blocksFor(kind: Kind, chapter: Chapter, entry: Entry, part: number): PageBlock[] {
  const head = [
    text({ x: 8, y: 5, w: 70, text: `Глава ${chapter.n} · ${chapter.title}`, font: "sans", size: "sm", color: "#8e3d52" }),
    text({ x: 8, y: 9, w: 84, text: part > 1 ? "" : entry.title, size: "lg", placeholder: part > 1 ? "Продолжение" : undefined }),
  ];
  const body = (y: number, w = 84, x = 8, size: Text["size"] = "md") => text({ x, y, w, size, placeholder: entry.desc });
  switch (kind) {
    case "photo":
      return [...head, slot(8, 20, 84, 54, "Главная фотография", "none"), text({ x: 8, y: 79, w: 84, font: "script", size: "md", placeholder: `Подпись: ${entry.desc}` })];
    case "person":
      return [
        ...head,
        slot(8, 20, 38, 44, "Портрет", "polaroid", -2),
        pill(52, 21, 40, "Имя"),
        text({ x: 52, y: 26, w: 40, font: "script", size: "md", placeholder: "впишите" }),
        pill(52, 35, 40, "Годы жизни"),
        text({ x: 52, y: 40, w: 40, font: "script", size: "md", placeholder: "впишите" }),
        pill(52, 49, 40, "Где жил(а)"),
        text({ x: 52, y: 54, w: 40, font: "script", size: "md", placeholder: "впишите" }),
        body(69, 84, 8, "sm"),
      ];
    case "tree": {
      const row = (y: number, labels: string[], w: number) =>
        labels.flatMap((label, i) => {
          const gap = (84 - w * labels.length) / Math.max(1, labels.length - 1);
          const x = labels.length === 1 ? 50 - w / 2 : 8 + i * (w + gap);
          return [slot(x, y, w, w * 0.9, label, "sticker"), text({ x, y: y + w * 0.9 + 1, w, font: "sans", size: "sm", align: "center", placeholder: "имя, годы" })];
        });
      return [
        ...head,
        ...row(20, ["Прадедушка", "Прабабушка", "Прадедушка", "Прабабушка"], 17),
        ...row(46, ["Дедушка", "Бабушка"], 20),
        ...row(73, ["Их дети и внуки"], 20),
      ];
    }
    case "timeline":
      return [
        ...head,
        ...Array.from({ length: 6 }, (_, i) => [pill(8, 21 + i * 11, 15, ""), text({ x: 26, y: 21 + i * 11, w: 66, size: "sm", placeholder: i === 0 ? entry.desc : "событие" })]).flat(),
      ].map((b) => (b.type === "text" && b.look === "pill" && !b.text ? { ...b, placeholder: "год" } : b));
    case "map":
      return [...head, slot(8, 20, 56, 52, "Карта или схема мест", "none"), text({ x: 68, y: 21, w: 24, font: "script", size: "sm", placeholder: "1. …\n2. …\n3. …\n4. …" }), body(77, 84, 8, "sm")];
    case "list":
      return [...head, text({ x: 8, y: 20, w: 56, font: "script", size: "md", placeholder: "1. …\n2. …\n3. …\n4. …\n5. …\n6. …" }), slot(66, 22, 26, 30, "Фото", "tape", 3), text({ x: 8, y: 80, w: 60, font: "sans", size: "sm", look: "card", text: entry.desc, rotate: -1 })];
    case "doc":
      return [
        ...head,
        slot(8, 20, 50, 60, "Скан документа", "none", -1),
        pill(62, 21, 30, "Что это"),
        text({ x: 62, y: 26, w: 30, size: "sm", placeholder: "название, год, откуда" }),
        pill(62, 44, 30, "Что он доказывает"),
        text({ x: 62, y: 49, w: 30, size: "sm", placeholder: "простыми словами" }),
        body(84, 84, 8, "sm"),
      ];
    case "compare":
      return [...head, slot(8, 21, 40, 42, "Тогда", "polaroid", -2), slot(52, 23, 40, 42, "Сейчас", "polaroid", 2), body(70)];
    case "recipe":
      return [
        ...head,
        slot(8, 20, 46, 36, "Блюдо или кухня", "tape", -2),
        pill(60, 21, 32, "Чья рука"),
        text({ x: 60, y: 26, w: 32, font: "script", size: "md", placeholder: "впишите" }),
        pill(8, 61, 40, "Что нужно"),
        text({ x: 8, y: 66, w: 40, font: "script", size: "sm", placeholder: "мука, яйца, щепотка…" }),
        pill(52, 61, 40, "Как готовили"),
        text({ x: 52, y: 66, w: 40, font: "script", size: "sm", placeholder: entry.desc }),
      ];
    case "letter":
      return [
        text({ x: 8, y: 5, w: 70, text: `Глава ${chapter.n} · ${chapter.title}`, font: "sans", size: "sm", color: "#8e3d52" }),
        text({ x: 10, y: 20, w: 80, text: entry.title, size: "lg", align: "center" }),
        text({ x: 12, y: 34, w: 76, font: "script", size: "md", align: "center", placeholder: entry.desc }),
        { id: id(), type: "sticker", kind: "branch", x: 40, y: 82, w: 20 },
      ];
    default:
      return [...head, body(20, 54), slot(66, 21, 26, 30, "Фото", "polaroid", 3), text({ x: 8, y: 60, w: 84, size: "sm", placeholder: "Продолжайте здесь…" })];
  }
}

/** 99 страниц после обложки — в порядке глав. */
export function fullBookPages(): Omit<BookPage, "id">[] {
  const out: Omit<BookPage, "id">[] = [];
  for (const chapter of FULL_BOOK) {
    for (const entry of chapter.pages) {
      entry.kinds.forEach((kind, i) => {
        const title = entry.kinds.length > 1 ? `${entry.title} (${i + 1}/${entry.kinds.length})` : entry.title;
        out.push({ title, kind: "page", paper: chapter.paper, promptId: `full:${chapter.n}:${entry.title}:${i}`, strokes: [], blocks: blocksFor(kind, chapter, entry, i + 1) });
      });
    }
  }
  return out;
}

export const FULL_BOOK_PAGES = FULL_BOOK.reduce((sum, chapter) => sum + chapter.pages.reduce((s, page) => s + page.kinds.length, 0), 0);
