export function todayTask(input: {
  hasCover: boolean;
  hasInk: boolean;
  handwriting: boolean;
  photos: number;
  people: number;
  maidenGap: string | null;
  interviews: number;
  unusedPrompt: string | null;
}): { title: string; detail: string } {
  if (!input.hasCover) {
    return {
      title: "Откройте обложку",
      detail: input.handwriting
        ? "Напишите, для кого книга. Одной строки достаточно."
        : "Напишите с клавиатуры, для кого книга. Одной строки достаточно.",
    };
  }
  if (input.handwriting && !input.hasInk) {
    return {
      title: "Оставьте одну фразу почерком",
      detail: "Стилусом или мышью. Потом можно оставить как есть или перевести в шрифт.",
    };
  }
  if (!input.handwriting && !input.hasInk) {
    return {
      title: "Напишите одну строку",
      detail: "На телефоне книга собирается текстом. Почерк откроется на планшете и компьютере.",
    };
  }
  if (input.maidenGap) {
    return {
      title: "Спросите девичью фамилию",
      detail: `${input.maidenGap}: где она жила в десять лет и как её звали до свадьбы.`,
    };
  }
  if (input.photos === 0) {
    return {
      title: "Положите на страницу одну фотографию",
      detail: "Старую. Подпишите, кто и где — даже если год примерный.",
    };
  }
  if (input.people === 0) {
    return {
      title: "Впишите одного человека",
      detail: "Того, с кого хотите начать. Имени и родства хватит.",
    };
  }
  if (input.interviews === 0) {
    return {
      title: "Запишите короткий разговор",
      detail: "Пять минут с мамой уже могут стать несколькими страницами.",
    };
  }
  if (input.unusedPrompt) {
    return {
      title: "Пустая страница уже ждёт",
      detail: input.unusedPrompt,
    };
  }
  return {
    title: "Добавьте одну деталь, которую помните только вы",
    detail: "Запах, фраза, смешной случай. Книга жива, пока её продолжают.",
  };
}
