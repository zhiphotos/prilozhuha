/**
 * Слова абзаца без потери пробелов: несколько пробелов подряд внутри текста человек ставит сам (место под дату другим шрифтом,
 * разрядка), поэтому лишние пробелы при переносе строк не склеиваются. Первый пробел остаётся обычным разделителем (по нему идёт перенос),
 * остальные становятся неразрывными и прикрепляются к концу предыдущего слова. Пробелы в начале абзаца обрабатывает вызывающий код.
 */
export function splitWords(paragraph: string): string[] {
  const body = paragraph.replace(/^[ \t]+/, "");
  const found = [...body.matchAll(/(\S+)([ \t]*)/g)];
  return found.map((m, i) => (i < found.length - 1 && m[2]!.length > 1 ? m[1]! + " ".repeat(m[2]!.length - 1) : m[1]!));
}
