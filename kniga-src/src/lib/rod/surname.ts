function variantsFor(raw: string, normalized: string): string[] {
  const set = new Set<string>();
  const push = (value: string) => {
    const next = value.trim();
    if (!next) return;
    if (next.toLowerCase() === raw.trim().toLowerCase()) return;
    set.add(next);
  };
  push(titleCase(raw));
  for (const [plain, yo] of YO) {
    if (normalized.includes(plain)) {
      push(titleCase(normalized.replace(plain, yo)));
    }
  }
  if (/(ов|ев|ин|ын|ий|ой)$/.test(normalized)) push(`${titleCase(normalized)}ъ`);
  if (/(ова|ева|ина|ына)$/.test(normalized)) {
    const male = normalized.slice(0, -1);
    push(titleCase(male));
    if (/(ов|ев|ин|ын)$/.test(male)) push(`${titleCase(male)}ъ`);
  }
  if (/(ов|ев|ин|ын)$/.test(normalized)) push(titleCase(`${normalized}а`));
  return [...set].slice(0, 4);
}

export function explainSurname(rawSurname: string, region: string, known: string): SurnameReading | { error: string } {
  const raw = rawSurname.trim().replace(/\s+/g, " ");
  if (raw.length < 2) return { error: "Впишите фамилию — хотя бы две буквы." };
  const token = raw.split(" ").at(-1) ?? raw;
  const normalized = normalize(token);
  const masculine = /(ова|ева|ина|ына)$/.test(normalized) ? normalized.slice(0, -1) : normalized;
  const notePrefix = token !== raw ? `Разобрана последняя часть: ${titleCase(token)}. ` : "";
  const { stem, suffix } = stripSuffix(normalized);
  const special = SPECIAL[normalized] ?? SPECIAL[masculine];
  const found = findRoot(stem, normalized);
  const shape = suffixStory(suffix, stem);
  const regionClean = region.trim();

  const origin = special
    ? `${notePrefix}${special.origin}`
    : found
      ? `${notePrefix}Возможное происхождение: основа связана с ${found.root.kind === "имя" ? "именем" : found.root.kind === "занятие" ? "занятием" : found.root.kind === "место" ? "местом или прозванием" : "прозвищем"}. ${cap(found.root.meaning)}.`
      : `${notePrefix}Готового значения для основы «${stem || normalized}» в этом справочнике нет. Ниже — только возможное устройство слова, не перевод «кто ваши предки».`;

  const formation = special ? special.formation : shape.formation;

  const regions = [...shape.regions];
  if (regionClean) {
    regions.unshift(`Вы указали: ${regionClean}. Искать стоит ветку там, а не всех однофамильцев страны`);
  }

  const next = [
    regionClean
      ? `Метрические книги и ревизские сказки именно в регионе «${regionClean}», плюс соседние приходы, если семья переезжала.`
      : "Сначала место: где семья жила в конце XIX — начале XX века. Без села фамилия почти не ищется.",
    "Девичья фамилия матери и бабушки. По ней часто находится вторая половина рода, которой нет в вашей сегодняшней фамилии.",
    "Как фамилию писали до 1918 года: е или ё, i или и, твёрдый знак на конце, мужская форма у женщины.",
    "Не считать однофамильца родственником, пока нет цепочки: имя, отчество, село, документ.",
  ];

  const knownNote = known.trim()
    ? `Вы уже знаете о семье вот это: «${known.trim()}». Сверьте рассказ с бумагой. Устная версия ценна сама по себе, даже если документ скажет чуть иначе.`
    : "Если пока известно только написание — так и запишите. Пустое «что мы знаем» честнее выдуманной легенды.";

  return {
    surname: titleCase(token),
    origin,
    formation,
    variants: variantsFor(token, normalized),
    regions,
    next,
    knownNote,
  };
}

function cap(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
