function normalize(value: string): string {
  return value.trim().toLowerCase().replaceAll("ё", "е").replace(/\s+/g, " ");
}

function capWord(word: string): string {
  if (!word) return word;
  return word.charAt(0).toUpperCase() + word.slice(1);
}

function titleCase(value: string): string {
  return value
    .split(/([\s-])/)
    .map((part) => (/[\s-]/.test(part) ? part : capWord(part.toLowerCase())))
    .join("");
}

function stripSuffix(surname: string): { stem: string; suffix: string } {
  for (const suffix of SUFFIXES) {
    if (surname.length - suffix.length >= 3 && surname.endsWith(suffix)) {
      return { stem: surname.slice(0, -suffix.length), suffix };
    }
  }
  return { stem: surname, suffix: "" };
}

function findRoot(stem: string, full: string): { key: string; root: Root } | null {
  if (ROOTS[full]) return { key: full, root: ROOTS[full] };
  if (ROOTS[stem]) return { key: stem, root: ROOTS[stem] };
  const keys = Object.keys(ROOTS).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (key.length < 4) continue;
    if (stem.startsWith(key) && stem.length - key.length <= 3) return { key, root: ROOTS[key] };
  }
  return null;
}

