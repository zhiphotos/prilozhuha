export function reminder(audience: Audience | null, dedicatee: string): string {
  const name = dedicatee.trim();
  const child = name || "ваш ребёнок";
  const lines: Record<Audience, string[]> = {
    self: [
      "Ты собираешь это не ради дерева. Однажды ты откроешь страницу и услышишь собственную семью яснее.",
      "Имена без сцен забываются первыми. Одна фраза мамы уже держит главу.",
    ],
    children: [
      `Ты собираешь это не ради дерева. Однажды ${child} сможет открыть эту страницу и узнать, какой была бабушка в двадцать лет.`,
      `${child} не спросит про дерево. ${cap(child)} спросит, какой была жизнь до него.`,
    ],
    future: [
      `Ты собираешь это не ради дерева. Однажды ${child} откроет эту страницу и увидит, из какой истории он вырос.`,
      "Будущему ребёнку не нужна полная родословная. Ему нужен голос тех, кого он не застанет.",
    ],
    parents: [
      "Ты собираешь это не ради дерева. Родителям важно успеть услышать, что их жизнь кому-то нужна целиком.",
      "Пока старшие ещё могут поправить вашу запись — это и есть лучшее время для книги.",
    ],
    family: [
      "Ты собираешь это не ради дерева. Однажды вся семья сможет открыть одну страницу и узнать себя.",
      "Общая книга начинается с одного человека, который согласился записывать.",
    ],
  };
  const pool = audience ? lines[audience] : lines.family;
  const day = Math.floor(Date.now() / 86_400_000);
  return pool[day % pool.length] ?? pool[0];
}

function cap(value: string): string {
  if (!value) return value;
  return value.charAt(0).toUpperCase() + value.slice(1);
}

